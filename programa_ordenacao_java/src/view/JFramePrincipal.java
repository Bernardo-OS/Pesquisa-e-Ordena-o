    /**
     * Função do botão gerar (chama função de gerar lista com valores aleatórios capturando valores das entradas)
     */
    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {                                             
        try {
        // Captura os dados digitados pelo usuário nas caixas de texto
        int quantidade = Integer.parseInt(jTextFieldQtdGerar.getText().trim());
        int minimo = Integer.parseInt(jTextFieldValMin.getText().trim());
        int maximo = Integer.parseInt(jTextFieldValMax.getText().trim());

        // Validações básicas de segurança para evitar travamentos
        if (quantidade <= 0) {
            JOptionPane.showMessageDialog(this, "A quantidade de números deve ser maior que zero.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (minimo > maximo) {
            JOptionPane.showMessageDialog(this, "O valor mínimo não pode ser maior que o valor máximo.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Chama a função para gerar aleatorios no Util.java (Controller)
        controller.Util.gerarListaAleatoria(quantidade, minimo, maximo);

        // Limpa o painel de resultados antigo e avisa que deu certo
        jPanelResultados.setVisible(false);
        jTextFieldNomeArquivo.setText("[Lista Aleatória Gerada]");//Bloqueia para caminho de arquivo
        
        JOptionPane.showMessageDialog(this, "Lista com " + quantidade + " números gerada com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);

    } catch (NumberFormatException e) {
        // Controle de exceção caso o usuário digite letras ou deixe campos vazios
        JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos de geração apenas com números inteiros válidos.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
    }
    }                                            

