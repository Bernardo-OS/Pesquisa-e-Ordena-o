    private void jButtonExecutarActionPerformed(java.awt.event.ActionEvent evt) {                                                
        if (Model.lista == null || Model.lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Lista está vazia", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        jPanelResultados.setVisible(true);
        jTextFieldQtdNumeros.setText("" + Model.lista.size());

        // Captura o modelo de dados da tabela
        DefaultTableModel modeloTabela = (DefaultTableModel) jTableResultados.getModel();
        modeloTabela.setRowCount(0);//limpa as linhas antigas

        String[] nomesMetodos = {"Bolha", "Inserção", "Pente", "Seleção", "Merge", "Quick"};

        
        float compSelecionado = 0, trocasSelecionado = 0, tempoSelecionado = 0;

        // Executa e popula todos os métodos na tabela comparativa
        for (int i = 0; i < 6; i++) {
            // Cria uma cópia isolada para não estragar (ordenar) a lista original do modelo
            ArrayList<Integer> listaCopia = new ArrayList<>(Model.lista);
            ArrayList<Float> metricasMetodo = new ArrayList<>();

            long tempoInicio = System.nanoTime();

            switch (i) {
                case 0: metricasMetodo.addAll(controller.Ordenacao.bolha(listaCopia)); break;
                case 1: metricasMetodo.addAll(controller.Ordenacao.insercao(listaCopia)); break;
                case 2: metricasMetodo.addAll(controller.Ordenacao.pente(listaCopia)); break;
                case 3: metricasMetodo.addAll(controller.Ordenacao.selecao(listaCopia)); break;
                case 4: metricasMetodo.addAll(controller.Ordenacao.merge(listaCopia)); break;
                case 5: metricasMetodo.addAll(controller.Ordenacao.quick(listaCopia)); break;
                default: throw new AssertionError();
            }

            long tempoFim = System.nanoTime();
            float tempoMilisegundos = (float) (tempoFim - tempoInicio) / 1000000;

            float comparacoes = metricasMetodo.get(0);
            float trocas = metricasMetodo.get(1);

            

            // O Java fará o autoboxing para Float atendendo às regras das colunas da JTable.
            modeloTabela.addRow(new Object[]{
                nomesMetodos[i], 
                comparacoes, 
                trocas, 
                tempoMilisegundos
            });
        }
    }

    
